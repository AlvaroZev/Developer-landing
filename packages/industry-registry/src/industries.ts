/**
 * Industry catalog. Visual identity comes from the theme system. Compatible
 * solutions come from the solution registry. This file owns the industry's
 * name, description, metrics, and the vocabulary the demo seeds speak.
 *
 * To add an industry: add a record here, a theme with the same slug, and the
 * pairs it supports in `compatibility`. The registry tests pick it up.
 */
export interface LocaleCopy {
  en: string;
  es: string;
}

export interface IndustryFlavor {
  people: string[];
  orgs: string[];
  places: string[];
  items: string[];
  services: string[];
  assets: string[];
  currency: string;
  taxRate: number;
}

export interface IndustryDefinition {
  slug: string;
  name: LocaleCopy;
  description: LocaleCopy;
  capabilities: LocaleCopy[];
  metrics: LocaleCopy[];
  featured: boolean;
  theme: IndustryTheme;
  flavor: IndustryFlavor;
  solutionSlugs: readonly string[];
}

const copy = (en: string, es: string): LocaleCopy => ({ en, es });

